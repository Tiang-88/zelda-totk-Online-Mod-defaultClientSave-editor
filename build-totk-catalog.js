#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = __dirname;
const sourceRoot = path.join(root, 'zelda-totk');

function read(relativePath) {
  return fs.readFileSync(path.join(sourceRoot, relativePath), 'utf8');
}

function createContext() {
  const context = {
    console,
    Locale: {
      add(language, strings) {
        if (language === 'en') context.englishNames = strings;
      }
    },
    Variable: {
      enumToInt(value) { return value; },
      enumToString(value) { return value; }
    },
    Pouch: {},
    _: value => value,
    document: {},
    Image: function Image() {}
  };
  vm.createContext(context);
  vm.runInContext(read('lib/murmurhash3js.min.js'), context);
  context.hash = value => context.murmurHash3.x86.hash32(value);
  context.hashReverse = value => String(value);
  return context;
}

function run(context, relativePath) {
  vm.runInContext(read(relativePath), context, { filename: relativePath });
}

function signedHash(context, value) {
  return context.hash(value) | 0;
}

function iconFiles(category) {
  const directory = path.join(sourceRoot, 'assets', 'item_icons', category);
  if (!fs.existsSync(directory)) return new Set();
  return new Set(fs.readdirSync(directory).filter(file => file.endsWith('.png')));
}

const context = createContext();
run(context, 'zelda-totk.class.item.js');
run(context, 'zelda-totk.class.equipment.js');
run(context, 'zelda-totk.class.armor.js');
run(context, 'locale/zelda-totk.locale.en.js');

const idsByCategory = {
  weapons: context.Equipment.AVAILABILITY.weapons,
  bows: context.Equipment.AVAILABILITY.bows,
  shields: context.Equipment.AVAILABILITY.shields,
  armors: context.Armor.AVAILABILITY,
  arrows: context.Item.AVAILABILITY.arrows,
  materials: context.Item.AVAILABILITY.materials,
  food: context.Item.AVAILABILITY.food,
  devices: context.Item.AVAILABILITY.devices,
  key: context.Item.AVAILABILITY.key
};

const catalogs = {};
for (const [category, ids] of Object.entries(idsByCategory)) {
  const availableIcons = iconFiles(category);
  const iconByName = new Map();
  for (const file of availableIcons) {
    const id = file.slice(0, -4);
    const name = context.englishNames[id];
    if (name && !iconByName.has(name)) iconByName.set(name, file);
  }

  catalogs[category] = ids.map(id => {
    const name = context.englishNames[id] || id;
    const exactIcon = `${id}.png`;
    const iconFile = availableIcons.has(exactIcon) ? exactIcon : iconByName.get(name);
    return {
      id,
      name,
      icon: iconFile ? `zelda-totk/assets/item_icons/${category}/${iconFile}` : 'zelda-totk/assets/item_icons/unknown.png'
    };
  });
}

catalogs.abilities = [
  ['UltraHand', 'Ultrahand'],
  ['OneTouchBond', 'Fuse'],
  ['Tooreroof', 'Ascend'],
  ['ReverseRecorder', 'Recall'],
  ['AutoBuilder', 'Autobuild'],
  ['AmiiboItem', 'Amiibo']
].map(([id, name]) => ({ id, name, icon: 'zelda-totk/assets/item_icons/unknown.png' }));

const enumNames = [
  'None', 'AttackUp', 'AttackUpPlus', 'DurabilityUp', 'DurabilityUpPlus',
  'FinishBlow', 'LongThrow', 'RapidFire', 'FiveWay', 'GuardUp', 'GuardUpPlus',
  'Blue', 'Red', 'Yellow', 'White', 'Black', 'Purple', 'Green', 'LightBlue',
  'Navy', 'Orange', 'Pink', 'Crimson', 'LightYellow', 'Brown', 'Gray',
  ...context.Item.FOOD_EFFECTS_RAW
];

const catalog = {
  generatedFrom: 'zelda-totk',
  categories: catalogs,
  durability: context.Equipment.DEFAULT_DURABILITY,
  fuseDurability: context.Equipment.FUSE_DURABILITY,
  enumHashes: Object.fromEntries([...new Set(enumNames)].map(name => [name, signedHash(context, name)]))
};

const output = `/* Generated by build-totk-catalog.js from the included zelda-totk project. */\nwindow.TOTK_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'totk-catalog.js'), output);
console.log(`Generated totk-catalog.js with ${Object.values(catalogs).flat().length} items.`);
